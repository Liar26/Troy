const norm = (s) => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
function famousOf(artist) {
  const a = norm(artist); if (!a) return null;
  return FAMOUS.find((f) => new RegExp(norm(f.re.source), 'i').test(a) && !(f.not && new RegExp(norm(f.not.source), 'i').test(a))) || null;
}
const isFamous = (artist) => !!famousOf(artist);
